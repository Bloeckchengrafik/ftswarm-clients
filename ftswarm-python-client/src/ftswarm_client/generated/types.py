class MicrostepMode(Enum):
    Full = 0
    Half = 4
    Quarter = 2
    Eighth = 6
    Sixteenth = 7

    @property
    def wire_value(self) -> int:
        return int(self.value)

    @classmethod
    def from_wire_value(cls, value: str) -> MicrostepMode:
        return cls(int(value))
